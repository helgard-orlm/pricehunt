function guess() {
  const l = (typeof navigator !== "undefined" && navigator.language || "en").slice(0, 2).toLowerCase();
  return D[l] ? l : "en";
}

let lang = guess();
export const getLang = () => lang;
export function setLang(l) { if (D[l]) lang = l; }

/** t("ключ", {имя: значение}) — строка на текущем языке; нет перевода — английская. */
export function t(key, vars) {
  const s = D[lang][key] ?? D.en[key] ?? key;
  return vars ? s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m)) : s;
}

/** Перевести статичную разметку: data-i18n (текст), data-i18n-html, data-i18n-ph (placeholder), data-i18n-title. */
export function applyDom(root = document) {
  root.documentElement && (root.documentElement.lang = lang);
  for (const el of root.querySelectorAll("[data-i18n]")) el.textContent = t(el.dataset.i18n);
  for (const el of root.querySelectorAll("[data-i18n-html]")) el.innerHTML = t(el.dataset.i18nHtml);
  for (const el of root.querySelectorAll("[data-i18n-ph]")) el.placeholder = t(el.dataset.i18nPh);
  for (const el of root.querySelectorAll("[data-i18n-title]")) el.title = t(el.dataset.i18nTitle);
}

// проверка полноты словарей (для тестов): ключи, которых нет в каком-то языке
export function missingKeys() {
  const all = Object.keys(D.en);
  return Object.fromEntries(Object.keys(D).map((l) => [l, all.filter((k) => !(k in D[l]))]));
}
